// EventDriven.tsx — Generic event-driven video composition
//
// This is the SINGLE generic composition for the event-driven pipeline.
// It loads video-specific data from a manifest file generated at render time.
//
// Data flow:
// 1. Workflow receives video_id input (e.g., "credit-score")
// 2. Workflow validates src/videos/{video_id}/data/event_timeline.json exists
// 3. Workflow generates src/videos/_active/manifest.json:
//    { "videoId": "credit-score", "timeline": "...", "audio": "..." }
// 4. This composition imports the manifest (static import works with Remotion)
// 5. EventDrivenVideo renders using the manifest's timeline and audio
//
// No video-specific code. No hardcoded paths. The manifest is data.

import React from "react";
import { EventDrivenVideo } from "./light/EventDrivenVideo";

// Manifest is generated by the workflow before rendering.
// See: .github/workflows/render-production.yml "Prepare event-driven manifest" step.
// Format: { "videoId": string, "timelinePath": string, "audioPath": string }
// The timeline and audio are imported via the manifest's resolved paths.
import manifest from "./videos/_active/manifest.json";
import timelineData from "./videos/_active/timeline.json";
import voAudio from "./videos/_active/vo.wav";

// F-08: Duration derives from the timeline (not hardcoded).
// Uses the last event's end_frame; falls back to 3379 if timeline is empty.
const _lastEnd = timelineData.events.length > 0
  ? Math.max(...timelineData.events.map((e: any) => e.end_frame))
  : 3379;
export const EVENT_DRIVEN_TOTAL = _lastEnd;

export const EventDriven: React.FC = () => {
  return (
    <EventDrivenVideo
      timeline={timelineData}
      audioSrc={voAudio}
    />
  );
};
